const LANG_KEY = 'nissei-lang';

function applyLanguage(lang) {
    const t = translations[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) el.textContent = t[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (t[key] !== undefined) el.innerHTML = t[key];
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (t[key] !== undefined) el.placeholder = t[key];
    });

    document.querySelectorAll('[data-i18n-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-label');
        if (t[key] !== undefined) {
            const firstNode = Array.from(el.childNodes).find(n => n.nodeType === Node.TEXT_NODE);
            if (firstNode) firstNode.textContent = t[key];
        }
    });

    document.querySelectorAll('.header__lang-btn, .mobile-nav__lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
}

document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem(LANG_KEY) || 'jp';
    applyLanguage(saved);

    document.querySelectorAll('.header__lang-btn, .mobile-nav__lang-btn').forEach(btn => {
        btn.addEventListener('click', () => applyLanguage(btn.dataset.lang));
    });
});
